import { expect, test } from '@playwright/test'
import { entrarComo, irPara, semRolagemLateral, USUARIOS, vigiarConsole } from './apoio'

test('dashboard do gestor: vendas do mês, ranking, metas e mês anterior', async ({ page }) => {
  const erros = vigiarConsole(page)
  await entrarComo(page, USUARIOS.gestor)
  await expect(page.getByTestId('kpi-vendas')).toHaveText('5 cotas')
  await expect(page.getByTestId('kpi-volume')).toHaveText('R$ 970.000,00')
  await expect(page.getByTestId('kpi-abertas')).toHaveText('4')
  await expect(page.getByText('1º Marcos Prado')).toBeVisible()
  await expect(page.getByTestId('meta-u-vend-2')).toContainText('95,0%')
  await expect(page.getByTestId('meta-u-vend-1')).toContainText('66,7%')
  await semRolagemLateral(page)
  const segmentos = page.getByRole('group', { name: 'Período' }).getByRole('button')
  await segmentos.nth(1).click()
  await expect(page.getByTestId('kpi-vendas')).toHaveText('3 cotas')
  await expect(page.getByTestId('kpi-volume')).toHaveText('R$ 690.000,00')
  expect(erros).toEqual([])
})

test('dashboard da vendedora mostra só os números dela', async ({ page }) => {
  await entrarComo(page, USUARIOS.vendedora)
  await expect(page.getByTestId('kpi-vendas')).toHaveText('3 cotas')
  await expect(page.getByTestId('kpi-volume')).toHaveText('R$ 400.000,00')
  await expect(page.getByTestId('meta-u-vend-1')).toBeVisible()
  await expect(page.getByTestId('meta-u-vend-2')).toHaveCount(0)
  await expect(page.locator('.ranking li[data-eu="true"]')).toContainText('Júlia Souza')
  await irPara(page, 'grupos')
  await expect(page.getByRole('heading', { name: 'Acesso não permitido' })).toBeVisible()
})

test('grupos: ocupação, assembleia e ciclo de vida de um grupo novo', async ({ page }) => {
  const erros = vigiarConsole(page)
  page.on('dialog', (d) => d.accept())
  await entrarComo(page, USUARIOS.admin)
  await irPara(page, 'grupos')
  await expect(page.getByTestId('disponiveis-IM-301')).toHaveText('60')
  await semRolagemLateral(page)

  await page.getByRole('link', { name: 'Grupo IM-301' }).click()
  await page.getByLabel('Maior lance').fill('47,5')
  await page.getByLabel('Menor lance').fill('30')
  await page.getByRole('button', { name: 'Registrar assembleia' }).click()
  await expect(page.getByText('Assembleia registrada.')).toBeVisible()
  const primeira = page.locator('table[aria-label="Assembleias"] tbody tr').first()
  await expect(primeira.locator('td').first()).toHaveText('4')
  await expect(primeira).toContainText('47,5%')
  await semRolagemLateral(page)

  await irPara(page, 'grupos/novo')
  await page.getByLabel('Código').fill('ve21')
  await page.getByRole('button', { name: 'Criar grupo' }).click()
  await expect(page.getByText('Use o formato IM-301')).toBeVisible()
  await page.getByLabel('Código').fill('VE-210')
  await page.getByLabel('Categoria').selectOption('veiculo')
  await page.getByRole('button', { name: 'Criar grupo' }).click()
  await expect(page.getByRole('heading', { name: 'Grupo VE-210' })).toBeVisible()
  await expect(page.getByText('Em formação')).toBeVisible()
  await page.getByRole('button', { name: 'Iniciar grupo' }).click()
  await expect(page.getByText('Grupo agora está em andamento.')).toBeVisible()
  expect(erros).toEqual([])
})

test('venda vinculada a grupo reduz as cotas disponíveis', async ({ page }) => {
  await entrarComo(page, USUARIOS.vendedora)
  await irPara(page, 'propostas/p-0012')
  await expect(page.getByLabel('Grupo da venda')).toHaveValue('g-ve-118')
  await page.getByRole('button', { name: 'Registrar venda' }).click()
  await expect(page.getByText('Proposta encerrada.')).toBeVisible()
  await expect(page.getByText('Grupo VE-118')).toBeVisible()

  await page.getByRole('button', { name: 'Sair' }).click()
  await entrarComo(page, USUARIOS.gestor)
  await irPara(page, 'grupos/g-ve-118')
  await expect(page.getByTestId('grupo-disponiveis')).toHaveText('46')
  await expect(page.getByRole('link', { name: /P-\d{4}-0012/ })).toBeVisible()
})

test('lance fixo no simulador usa o percentual do grupo escolhido', async ({ page }) => {
  await entrarComo(page, USUARIOS.vendedora)
  await irPara(page, 'simulador')
  await page.getByRole('button', { name: 'Lance', exact: true }).click()
  await page.getByRole('button', { name: 'Fixo' }).click()
  await expect(page.getByTestId('campo-lance')).toHaveValue('30')
  await page.getByLabel('Grupo').selectOption('g-im-305')
  await expect(page.getByTestId('campo-lance')).toHaveValue('25')
  await expect(page.getByText('Lance fixo (25,00% da carta)')).toBeVisible()
})

